/**
 * CarPlay + Android Auto native setup for the vendored @g4rb4g3/react-native-carplay.
 * Applied only when building with WAYLINE_CAR=1 (see app.config.ts and react-native.config.js).
 *
 * iOS:   com.apple.developer.carplay-maps entitlement (Apple must grant it to your team),
 *        a CarPlay scene (CPTemplateApplicationSceneSessionRoleApplication) next to Expo's phone
 *        scene, CarSceneDelegate.swift → RNCarPlay connect/disconnect, bridging-header import.
 * Android: com.google.android.gms.car.application meta-data + automotive_app_desc.xml. The
 *        library's own manifest already declares its CarAppService (navigation category).
 */
const fs = require('node:fs');
const path = require('node:path');
const {
  withAndroidManifest, withDangerousMod, withEntitlementsPlist, withInfoPlist, withXcodeProject, AndroidConfig, IOSConfig,
} = require('expo/config-plugins');

const CAR_SCENE = 'CPTemplateApplicationSceneSessionRoleApplication';

const SWIFT = `import CarPlay
internal import Expo
import React

/// Generated by plugins/withCar.js — hands the CarPlay interface to react-native-carplay.
@objc(CarSceneDelegate)
class CarSceneDelegate: UIResponder, CPTemplateApplicationSceneDelegate {
  func templateApplicationScene(_ templateApplicationScene: CPTemplateApplicationScene,
                                didConnect interfaceController: CPInterfaceController,
                                to window: CPWindow) {
    // Bridgeless React Native: CarPlay's React views come from the app's factory.
    RNCarPlay.setRootViewFactory { moduleName, initialProperties in
      guard let factory = (UIApplication.shared.delegate as? ExpoReactNativeFactoryProvider)?.reactNativeFactory else {
        return UIView()
      }
      return factory.rootViewFactory.view(withModuleName: moduleName, initialProperties: initialProperties)
    }
    RNCarPlay.connect(with: interfaceController, window: window)
  }

  func templateApplicationScene(_ templateApplicationScene: CPTemplateApplicationScene,
                                didDisconnect interfaceController: CPInterfaceController,
                                from window: CPWindow) {
    RNCarPlay.disconnect()
  }
}
`;

function withCarIos(config) {
  config = withEntitlementsPlist(config, (c) => {
    c.modResults['com.apple.developer.carplay-maps'] = true;
    return c;
  });

  config = withInfoPlist(config, (c) => {
    const manifest = c.modResults.UIApplicationSceneManifest ?? { UIApplicationSupportsMultipleScenes: false, UISceneConfigurations: {} };
    manifest.UISceneConfigurations = manifest.UISceneConfigurations ?? {};
    manifest.UISceneConfigurations[CAR_SCENE] = [
      {
        UISceneClassName: 'CPTemplateApplicationScene',
        UISceneConfigurationName: 'CarPlay',
        UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).CarSceneDelegate',
      },
    ];
    c.modResults.UIApplicationSceneManifest = manifest;
    return c;
  });

  config = withDangerousMod(config, ['ios', (c) => {
    const name = IOSConfig.XcodeUtils.getProjectName(c.modRequest.projectRoot);
    const dir = path.join(c.modRequest.platformProjectRoot, name);
    fs.writeFileSync(path.join(dir, 'CarSceneDelegate.swift'), SWIFT);
    const bridging = path.join(dir, `${name}-Bridging-Header.h`);
    const header = fs.existsSync(bridging) ? fs.readFileSync(bridging, 'utf8') : '';
    if (!header.includes('RNCarPlay.h')) fs.writeFileSync(bridging, `${header.trimEnd()}\n#import "RNCarPlay.h"\n`);
    return c;
  }]);

  config = withXcodeProject(config, (c) => {
    const name = IOSConfig.XcodeUtils.getProjectName(c.modRequest.projectRoot);
    const file = `${name}/CarSceneDelegate.swift`;
    if (!c.modResults.hasFile(file)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath: file, groupName: name, project: c.modResults });
    }
    return c;
  });
  return config;
}

function withCarAndroid(config) {
  config = withAndroidManifest(config, (c) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(c.modResults);
    AndroidConfig.Manifest.addMetaDataItemToMainApplication(app, 'com.google.android.gms.car.application', '@xml/automotive_app_desc', 'resource');
    return c;
  });
  config = withDangerousMod(config, ['android', (c) => {
    const dir = path.join(c.modRequest.platformProjectRoot, 'app/src/main/res/xml');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'automotive_app_desc.xml'), '<?xml version="1.0" encoding="utf-8"?>\n<automotiveApp>\n  <uses name="template" />\n</automotiveApp>\n');
    return c;
  }]);
  return config;
}

module.exports = function withCar(config) {
  return withCarAndroid(withCarIos(config));
};
